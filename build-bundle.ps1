# Bundles European CV Studio ES modules into:
# 1) js/app.bundle.js for file:// protocol compatibility
# 2) A standalone single-file HTML artifact (dist/ by default)
param(
  [string]$StandaloneArtifactPath = '',
  [switch]$SkipStandalone
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$files = @(
  'js/model/cv-schema.js',
  'js/model/storage.js',
  'js/engines/country-rules.js',
  'js/engines/ats-scorer.js',
  'js/engines/job-matcher.js',
  'js/engines/completion-engine.js',
  'js/engines/pdf-exporter.js',
  'js/components/preview-renderer.js',
  'js/app.js'
)

$sb = [System.Text.StringBuilder]::new()
# Emit LF only so the generated bundle is byte-identical on every platform and
# does not show up as modified after a rebuild (see .gitattributes).
$nl = "`n"
[void]$sb.Append("/**$nl")
[void]$sb.Append(" * AUTO-GENERATED CLASSIC BUNDLE FOR file:// PROTOCOL SUPPORT$nl")
[void]$sb.Append(" * Generated by build-bundle.ps1 from modular ES sources in js/$nl")
[void]$sb.Append(" */$nl")
[void]$sb.Append("(function () {$nl")
[void]$sb.Append("  'use strict';$nl")

foreach ($rel in $files) {
  $full = Join-Path $root $rel
  $raw = Get-Content -Path $full -Raw -Encoding UTF8
  $cleaned = [regex]::Replace($raw, '(?ms)^\s*import\s+(?:[\s\S]*?from\s+)?[''"][^''"]+[''"];?\s*$', '')
  $cleaned = [regex]::Replace($cleaned, '(?m)^\s*export\s+(?=(const|let|var|function)\s)', '')
  # Normalise source line endings so a CRLF checkout does not leak into the bundle.
  $cleaned = $cleaned.Replace("`r`n", "`n")
  [void]$sb.Append("  // --- $rel ---$nl")
  [void]$sb.Append("$cleaned$nl")
}

[void]$sb.Append("})();$nl")

$bundleCode = $sb.ToString()
$outPath = Join-Path $root 'js/app.bundle.js'
[System.IO.File]::WriteAllText($outPath, $bundleCode, [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated $outPath ($((Get-Item $outPath).Length) bytes)"

# Generate standalone artifact with inlined CSS and bundled JS
if (-not $SkipStandalone) {
  if (-not $StandaloneArtifactPath) {
    $StandaloneArtifactPath = Join-Path $root 'dist/european_cv_builder.html'
  }
  $artifactDir = Split-Path -Parent $StandaloneArtifactPath
  if (-not (Test-Path $artifactDir)) {
    New-Item -ItemType Directory -Path $artifactDir -Force | Out-Null
  }

  $indexHtml = Get-Content -Path (Join-Path $root 'index.html') -Raw -Encoding UTF8
  $cssPrint = Get-Content -Path (Join-Path $root 'css/print-a4.css') -Raw -Encoding UTF8
  $cssTpl = Get-Content -Path (Join-Path $root 'css/templates.css') -Raw -Encoding UTF8
  $cssApp = Get-Content -Path (Join-Path $root 'css/app.css') -Raw -Encoding UTF8

  $combinedCSS = "<style>`n$cssPrint`n$cssTpl`n$cssApp`n</style>"
  $standaloneHtml = [regex]::Replace(
    $indexHtml,
    '(?s)<link rel="stylesheet" href="css/print-a4\.css">.*?<link rel="stylesheet" href="css/app\.css">',
    { param($m) $combinedCSS }
  )

  # Avoid accidental </script> termination inside string literals if present
  $safeBundle = $bundleCode.Replace('</script>', '<\/script>')
  $inlineScript = "<script>`n$safeBundle`n</script>"
  $standaloneHtml = [regex]::Replace(
    $standaloneHtml,
    '(?s)<!-- Automatic Module vs File-Protocol Loader.*?</script>',
    { param($m) $inlineScript }
  )

  [System.IO.File]::WriteAllText($StandaloneArtifactPath, $standaloneHtml, [System.Text.UTF8Encoding]::new($false))
  Write-Host "Generated standalone artifact: $StandaloneArtifactPath ($((Get-Item $StandaloneArtifactPath).Length) bytes)"
}
